#!/usr/bin/env python3
"""Build and validate this bundle's small, documented token format (stdlib only)."""
import argparse
import json
import math
import re
import sys
from pathlib import Path
from urllib.parse import unquote

ROOT = Path(__file__).resolve().parents[1]
VERSION = "1.0.0"
ALIAS = re.compile(r"^\{([a-zA-Z0-9_.]+)\}$")
DIMENSION = re.compile(r"^(?:0|\d+(?:\.\d+)?(?:px|rem|em|ch))$")


def leaves(tree, prefix=""):
    for key, value in tree.items():
        path = f"{prefix}.{key}" if prefix else key
        if isinstance(value, dict) and "$value" in value:
            if set(value) != {"$type", "$value"}:
                raise ValueError(f"Unexpected token fields: {path}")
            yield path, value
        elif isinstance(value, dict):
            yield from leaves(value, path)
        else:
            raise ValueError(f"Malformed token: {path}")


def load(mode):
    result = {}
    for name in ("foundation", "motion", mode):
        doc = json.loads((ROOT / "tokens" / f"{name}.json").read_text(encoding="utf-8"))
        if doc["version"] != VERSION:
            raise ValueError(f"Version mismatch in {name}")
        if name == mode and doc["mode"] != mode:
            raise ValueError(f"Mode mismatch in {name}")
        for layer in ("primitive", "semantic", "component"):
            for path, token in leaves(doc.get(layer, {}), layer):
                if path in result:
                    raise ValueError(f"Duplicate token: {path}")
                result[path] = token
    return result


def resolve(tokens, path, trail=()):
    if path in trail:
        raise ValueError("Alias cycle: " + " -> ".join((*trail, path)))
    if path not in tokens:
        raise ValueError(f"Missing alias: {path}")
    token = tokens[path]
    value = token["$value"]
    alias = ALIAS.fullmatch(value) if isinstance(value, str) else None
    if alias:
        target = alias.group(1)
        if target not in tokens or tokens[target]["$type"] != token["$type"]:
            raise ValueError(f"Alias type/target mismatch: {path} -> {target}")
        return resolve(tokens, target, (*trail, path))
    return value


def variable(path):
    layer, rest = path.split(".", 1)
    prefix = {"primitive": "p-", "semantic": "", "component": "c-"}[layer]
    return "--itm-" + prefix + rest.replace(".", "-")


def declarations(tokens, paths):
    result = []
    for path in sorted(paths):
        value = tokens[path]["$value"]
        alias = ALIAS.fullmatch(value) if isinstance(value, str) else None
        css = f"var({variable(alias.group(1))})" if alias else str(value)
        result.append(f"  {variable(path)}: {css};")
    return "\n".join(result)


def build_css():
    light, dark = load("light"), load("dark")
    for tokens in (light, dark):
        for path in tokens:
            resolve(tokens, path)
    changed = {key for key in dark if key not in light or dark[key] != light[key]}
    # Repeat aliases in the dark scope too: inherited custom properties can
    # otherwise retain values computed against a light ancestor.
    themed = {key for key in dark if key.startswith("primitive.color.") or
              key.startswith("semantic.color.") or key.startswith("component.")}
    return ("/* Generated by scripts/tokens.py build. Edit JSON, then regenerate. */\n"
            ":root, [data-theme=\"light\"] {\n  color-scheme: light;\n" +
            declarations(light, light) + "\n}\n\n[data-theme=\"dark\"] {\n"
            "  color-scheme: dark;\n" + declarations(dark, changed | themed) + "\n}\n")


def luminance(value):
    channels = [int(value[i:i+2], 16) / 255 for i in (1, 3, 5)]
    linear = [c / 12.92 if c <= .04045 else ((c + .055) / 1.055) ** 2.4 for c in channels]
    return sum(a * b for a, b in zip(linear, (.2126, .7152, .0722)))


def contrast(a, b):
    low, high = sorted((luminance(a), luminance(b)))
    return (high + .05) / (low + .05)


def validate():
    errors, ratios = [], []
    themes = {mode: load(mode) for mode in ("light", "dark")}
    if set(themes["light"]) != set(themes["dark"]):
        errors.append("Theme token keys differ")
    for path in themes["light"].keys() & themes["dark"].keys():
        if themes["light"][path]["$type"] != themes["dark"][path]["$type"]:
            errors.append(f"Theme token type differs: {path}")
    for mode, tokens in themes.items():
        names = [variable(path) for path in tokens]
        if len(names) != len(set(names)):
            errors.append(f"{mode}: CSS variable name collision")
        for path, token in tokens.items():
            value, kind = resolve(tokens, path), token["$type"]
            valid = False
            if kind == "color":
                valid = isinstance(value, str) and re.fullmatch(r"#[0-9A-Fa-f]{6}", value)
            elif kind == "dimension":
                valid = isinstance(value, str) and DIMENSION.fullmatch(value)
            elif kind == "duration":
                valid = isinstance(value, str) and re.fullmatch(r"\d+ms", value)
            elif kind == "number":
                valid = type(value) in (int, float) and math.isfinite(value) and value >= 0
            elif kind == "fontFamily":
                valid = isinstance(value, str) and ";" not in value and bool(value.strip())
            elif kind == "shadow":
                valid = value == "none"
            if not valid:
                errors.append(f"{mode}: invalid {kind} at {path}: {value}")
        get = lambda role: resolve(tokens, "semantic.color." + role)
        for bg in ("canvas", "surface"):
            for fg in ("text", "muted", "accentText", "error", "info"):
                ratios.append((mode, fg, bg, contrast(get(fg), get(bg)), 4.5))
            for fg in ("border", "focus"):
                ratios.append((mode, fg, bg, contrast(get(fg), get(bg)), 3.0))
        for bg in ("selected", "selectedHover"):
            ratios.append((mode, "onSelected", bg, contrast(get("onSelected"), get(bg)), 4.5))
        motion = lambda key: resolve(tokens, "semantic.motion." + key)
        duration = int(motion("decorativeDuration")[:-2])
        fps, steps = motion("decorativeFps"), motion("decorativeSteps")
        if not (6 <= fps <= 12 and steps == int(steps) and steps * 1000 == fps * duration):
            errors.append(f"{mode}: decorative cadence must match integer steps at 6–12fps")
        cycle = int(motion("ambientCycle")[:-2])
        if cycle <= 0 or cycle * fps % 1000 != 0:
            errors.append(f"{mode}: ambient cycle must contain a whole number of frames")
        if not 6 <= motion("reactiveFps") <= 12:
            errors.append(f"{mode}: reactive cadence default must be 6-12fps")
        if motion("selectionDuration") != "0ms" or motion("selectionSteps") != 0:
            errors.append(f"{mode}: selection steps and duration must be zero")
        for prefix in ("feedback",):
            short_duration = int(motion(prefix + "Duration")[:-2]) if prefix == "selection" else int(motion("feedback")[:-2])
            short_steps = motion(prefix + "Steps")
            if short_steps < 1 or short_steps != int(short_steps) or short_steps * 1000 != fps * short_duration:
                errors.append(f"{mode}: {prefix} steps must match decorative cadence")
        if int(motion("cursorPeriod")[:-2]) < 1000:
            errors.append(f"{mode}: cursor blink too fast")
        if motion("interaction") != "0ms" or motion("reducedDuration") != "0ms":
            errors.append(f"{mode}: interaction and reduced-motion delay must be zero")
    for mode, fg, bg, actual, threshold in ratios:
        if actual < threshold:
            errors.append(f"{mode}: {fg}/{bg} {actual:.3f}:1 < {threshold}:1")
    md_links = re.compile(r"!?\[[^\]]*\]\(([^)]+)\)")
    for doc in ROOT.rglob("*.md"):
        content = doc.read_text(encoding="utf-8")
        # Ignore fenced code examples; they are not repository link promises.
        content = re.sub(r"```.*?```", "", content, flags=re.S)
        for target in md_links.findall(content):
            if "://" in target or target.startswith("#"):
                continue
            path = unquote(target.strip("<>").split("#")[0])
            if not (doc.parent / path).exists():
                errors.append(f"Broken local link in {doc.relative_to(ROOT)}: {target}")
    for mode in themes:
        subset = [row for row in ratios if row[0] == mode]
        lowest = min(subset, key=lambda row: row[3] / row[4])
        print(f"{mode}: {len(subset)} contrast pairs; tightest {lowest[1]}/{lowest[2]} "
              f"= {lowest[3]:.3f}:1 (required {lowest[4]:g}:1)")
    for error in errors:
        print("FAIL:", error, file=sys.stderr)
    if errors:
        return 1
    print("PASS: theme parity, aliases, values, contrast contracts, motion, and local Markdown links")
    return 0


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("build", "check", "validate"))
    args = parser.parse_args()
    try:
        if args.command == "validate":
            return validate()
        target, expected = ROOT / "tokens" / "generated.css", build_css()
        if args.command == "check":
            if not target.exists() or target.read_text(encoding="utf-8") != expected:
                print("FAIL: generated CSS is stale; run build", file=sys.stderr)
                return 1
            print("PASS: generated CSS matches JSON")
        else:
            target.write_text(expected, encoding="utf-8", newline="\n")
            print("Wrote", target.relative_to(ROOT))
        return 0
    except (ValueError, KeyError, OSError, TypeError) as error:
        print("FAIL:", error, file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
